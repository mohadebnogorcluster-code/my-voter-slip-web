export function getDivisionNames(): string[] {
  return BANGLADESH_GEO_DATA.map((d) => d.name);
}

export function getDistrictsByDivision(divisionName: string): string[] {
  const div = BANGLADESH_GEO_DATA.find((d) => d.name === divisionName);
  return div ? div.districts.map((dist) => dist.name) : [];
}

export function getUpazilasByDistrict(divisionName: string, districtName: string): string[] {
  const div = BANGLADESH_GEO_DATA.find((d) => d.name === divisionName);
  const dist = div?.districts.find((item) => item.name === districtName);
  return dist ? dist.upazilas : [];
}
